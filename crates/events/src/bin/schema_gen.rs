//! schema-gen — the deterministic generator for the committed `schema/`
//! artifacts, and the freshness gate that keeps them honest.
//!
//! The published contract — two JSON Schemas and the taxonomy inventory —
//! is generated from the types in this crate, never hand-written, so the one
//! failure mode a generated contract can have is the committed file lagging
//! the code. `--check` closes it: CI regenerates every artifact in memory
//! and fails on any byte difference from what is committed, which also makes
//! a hand-edit of an artifact a CI failure.
//!
//! Binary contract:
//!   schema-gen           # (re)write every artifact under schema/
//!   schema-gen --check   # exit non-zero if a committed artifact differs from the generated bytes
//!
//! Output is canonical (sorted keys, two-space indent, LF, trailing
//! newline), so a regeneration on any OS is byte-identical and the check is
//! a plain byte compare.

use std::path::{Path, PathBuf};
use std::process::exit;

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let check = match args.iter().map(String::as_str).collect::<Vec<_>>()[..] {
        [] => false,
        ["--check"] => true,
        _ => {
            eprintln!("schema-gen: usage: schema-gen [--check]");
            exit(2);
        }
    };

    // The artifacts live at the repository root; anchor on the crate
    // manifest so the path holds from any working directory.
    let schema_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../schema");
    let artifacts: [(&str, serde_json::Value); 3] = [
        ("events.schema.json", agent_bridge_events::event_schema()),
        (
            "trace-record.schema.json",
            agent_bridge_events::trace_record_schema(),
        ),
        (
            "event-taxonomy.json",
            agent_bridge_events::taxonomy_manifest(),
        ),
    ];

    let mut stale: Vec<PathBuf> = Vec::new();
    for (name, value) in artifacts {
        let rendered = agent_bridge_events::canonical_json(&value);
        let path = schema_dir.join(name);
        if check {
            match std::fs::read_to_string(&path) {
                Ok(committed) if committed == rendered => {
                    eprintln!("schema-gen: {name} is fresh");
                }
                Ok(_) => {
                    eprintln!("schema-gen: {name} differs from what the types generate");
                    stale.push(path);
                }
                Err(err) => {
                    eprintln!("schema-gen: {name} cannot be read ({err})");
                    stale.push(path);
                }
            }
        } else {
            if let Err(err) = std::fs::create_dir_all(&schema_dir) {
                eprintln!(
                    "schema-gen: creating {} failed: {err}",
                    schema_dir.display()
                );
                exit(1);
            }
            if let Err(err) = std::fs::write(&path, &rendered) {
                eprintln!("schema-gen: writing {} failed: {err}", path.display());
                exit(1);
            }
            eprintln!("schema-gen: wrote {}", path.display());
        }
    }

    if !stale.is_empty() {
        eprintln!(
            "schema-gen: the committed schema artifacts are stale (or hand-edited). \
             Regenerate them and commit the result:\n  cargo run -p agent-bridge-events --bin schema-gen"
        );
        exit(1);
    }
}
